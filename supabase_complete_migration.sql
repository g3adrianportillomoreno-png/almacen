ALTER TABLE public.expected_series ADD COLUMN IF NOT EXISTS system_status TEXT DEFAULT 'Principal';

-- 2. TABLA DE HISTORIAL DE BAJAS DE INVENTARIO (Conservación de 30 días)
CREATE TABLE IF NOT EXISTS public.inventory_departures (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  serial TEXT NOT NULL,
  material TEXT,
  internal_number TEXT,
  warehouse_name TEXT,
  warehouse_row TEXT,
  warehouse_space TEXT,
  system_status TEXT DEFAULT 'Principal',
  reason TEXT DEFAULT 'Baja por actualización de maestro',
  departure_date TIMESTAMPTZ DEFAULT NOW(),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_departures_date ON public.inventory_departures(departure_date);
CREATE INDEX IF NOT EXISTS idx_departures_serial ON public.inventory_departures(serial);

ALTER TABLE public.inventory_departures ENABLE ROW LEVEL SECURITY;

DO $$ 
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies 
    WHERE tablename = 'inventory_departures' AND policyname = 'Permitir todo a anon en inventory_departures'
  ) THEN
    CREATE POLICY "Permitir todo a anon en inventory_departures" 
    ON public.inventory_departures 
    FOR ALL 
    TO anon 
    USING (true) 
    WITH CHECK (true);
  END IF;
END $$;

-- 3. TABLAS PARA EL MÓDULO MERCADO LIBRE
-- 3.1 Lotes / Despachos
CREATE TABLE IF NOT EXISTS public.mercadolibre_batches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  folio TEXT,
  consecutive_number INTEGER,
  status TEXT DEFAULT 'pending',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3.2 Paquetes (Número de Guía y Número de Rastreo)
CREATE TABLE IF NOT EXISTS public.mercadolibre_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id BIGINT REFERENCES public.mercadolibre_batches(id) ON DELETE CASCADE,
  guide_number TEXT NOT NULL,
  tracking_number TEXT NOT NULL,
  is_scanned BOOLEAN DEFAULT false,
  scanned_at TIMESTAMPTZ,
  scanned_with TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3.3 Incidencias / Códigos Inesperados
CREATE TABLE IF NOT EXISTS public.mercadolibre_unexpected (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id BIGINT REFERENCES public.mercadolibre_batches(id) ON DELETE CASCADE,
  scanned_value TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_ml_items_batch ON public.mercadolibre_items(batch_id);
CREATE INDEX IF NOT EXISTS idx_ml_items_guide ON public.mercadolibre_items(guide_number);
CREATE INDEX IF NOT EXISTS idx_ml_items_tracking ON public.mercadolibre_items(tracking_number);

ALTER TABLE public.mercadolibre_batches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mercadolibre_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mercadolibre_unexpected ENABLE ROW LEVEL SECURITY;

