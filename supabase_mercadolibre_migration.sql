-- 1. Tabla de Lotes / Despachos de Mercado Libre
CREATE TABLE IF NOT EXISTS public.mercadolibre_batches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  folio TEXT,
  consecutive_number INTEGER,
  status TEXT DEFAULT 'pending',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Tabla de Paquetes (Número de Guía y Número de Rastreo)
CREATE TABLE IF NOT EXISTS public.mercadolibre_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id BIGINT REFERENCES public.mercadolibre_batches(id) ON DELETE CASCADE,
  guide_number TEXT NOT NULL,
  tracking_number TEXT NOT NULL,
  is_scanned BOOLEAN DEFAULT false,
  scanned_at TIMESTAMPTZ,
  scanned_with TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Tabla de Lecturas Inesperadas / Incidencias
CREATE TABLE IF NOT EXISTS public.mercadolibre_unexpected (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id BIGINT REFERENCES public.mercadolibre_batches(id) ON DELETE CASCADE,
  scanned_value TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Índices de búsqueda para lecturas de código de barras instantáneas
CREATE INDEX IF NOT EXISTS idx_ml_items_batch ON public.mercadolibre_items(batch_id);
CREATE INDEX IF NOT EXISTS idx_ml_items_guide ON public.mercadolibre_items(guide_number);
CREATE INDEX IF NOT EXISTS idx_ml_items_tracking ON public.mercadolibre_items(tracking_number);

-- 4. Habilitar Row Level Security (RLS) y Políticas para el rol anon
ALTER TABLE public.mercadolibre_batches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mercadolibre_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mercadolibre_unexpected ENABLE ROW LEVEL SECURITY;

DO $$ 
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies 
    WHERE tablename = 'mercadolibre_batches' AND policyname = 'Permitir todo a anon en mercadolibre_batches'
  ) THEN
    CREATE POLICY "Permitir todo a anon en mercadolibre_batches" 
    ON public.mercadolibre_batches 
    FOR ALL 
    TO anon 
    USING (true) 
    WITH CHECK (true);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies 
    WHERE tablename = 'mercadolibre_items' AND policyname = 'Permitir todo a anon en mercadolibre_items'
  ) THEN
    CREATE POLICY "Permitir todo a anon en mercadolibre_items" 
    ON public.mercadolibre_items 
    FOR ALL 
    TO anon 
    USING (true) 
    WITH CHECK (true);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies 
    WHERE tablename = 'mercadolibre_unexpected' AND policyname = 'Permitir todo a anon en mercadolibre_unexpected'
  ) THEN
    CREATE POLICY "Permitir todo a anon en mercadolibre_unexpected" 
    ON public.mercadolibre_unexpected 
    FOR ALL 
    TO anon 
    USING (true) 
    WITH CHECK (true);
  END IF;
END $$;
